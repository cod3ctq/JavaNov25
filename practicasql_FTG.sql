--VARIABLES DE SUSTITUCION
SELECT NOMBRE, DIRECCION FROM CLIENTES2
WHERE NOMBRE = '&NOM';

--REUTILIZAR LA MISMA VARIABLE
SELECT &&COLUMNA
FROM CLIENTES2
