--VALORES LOGICOS
--MUESTRA UNICAMENTE LOS VALORES QUE SEAN IGUALES O MAYORES QUE 3000 Y MENORES O IGUALES A 11000
--EN LA TABLA MONTO USANDO "AND"
SELECT MONTO FROM MOVIMIENTOS WHERE MONTO>=3000 AND MONTO<=11000;
--MUESTRA UNICAMENTE LOS VALORES DE TIPO"RETIRO Y DEPOSITO" DE LA COLUMNA TIPO_OPERACION USANDO "OR"
SELECT TIPO_OPERACION FROM MOVIMIENTOS WHERE TIPO_OPERACION='RETIRO' OR TIPO_OPERACION='DEPOSITO';
SELECT TIPO_OPERACION FROM MOVIMIENTOS WHERE TIPO_OPERACION>'A' AND TIPO_OPERACION<'Z';

--BETWEEN
--MUESTRA LOS VALORES QUE SE ENCUENTRAN ENTRE 30000 Y 11000 DE LA COLUMNA MONTO USANDO "BETWEEN"
SELECT MONTO FROM MOVIMIENTOS WHERE MONTO BETWEEN 3000 AND 11000;

--IN
--MUESTRA UNICAMENTE LOS VALORES QUE SE INGRESAN(1500,3300,11000) DE LA COLUMNA MONTO
SELECT MONTO FROM MOVIMIENTOS WHERE MONTO IN (1500,3300,11000);

SELECT * FROM MOVIMIENTOS;

--LIKE
--MUESTRA UNICAMENTE LAS PALABRAS QUE COMIENCEN CON LA LETRA "D" DE LA COLUMNA TIPO_OPERACION
SELECT TIPO_OPERACION FROM MOVIMIENTOS WHERE TIPO_OPERACION LIKE 'D%';
--MUESTRA UNICAMENTE LAS PALABRAS QUE CUENTES COLOS CARACTERES INGRESADOS "R_TIROS"
SELECT TIPO_OPERACION FROM MOVIMIENTOS WHERE TIPO_OPERACION LIKE 'R_TIRO';

--IS NULL
