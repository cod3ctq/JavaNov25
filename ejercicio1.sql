--ORDENACION
--ORDENA LOS VALORES DE LA COLUMNA MONTO DE MENOR A MAYOR EN FORMA ASCENDENTE
SELECT MONTO FROM MOVIMIENTOS ORDER BY MONTO;
--ORDENA LOS VALORES DE LA COLUMNA MONTO DE MAYOR A MENOR EN FORMA DESCENDENTE AL ESCRIBIR "DESC"
SELECT MONTO FROM MOVIMIENTOS ORDER BY MONTO DESC;

--ORDENA LAS COLUMNAS QUE SE LE INGRESAN (FECHA, TIPO_OPERACION,MONTO)
SELECT FECHA, TIPO_OPERACION, MONTO FROM MOVIMIENTOS ORDER BY 1,2,3 ;

--MANEJO DE NULOS EN LAS ORACIONES
-- NULLS LAST
-- NULLS FIRST

-- EN ESTE CASO TODAS LAS CASILLAS DE LA COLUMNA FECHA ESTAN LLENAS CON ALGUN VALOR PERO SI HUBIERA ALGUNA VACIA
--DEBERIA APARECER AL INICIO YA QUE SE ESTA USANDO EL "NULLS FIRST"
SELECT FECHA, TIPO_OPERACION, MONTO FROM MOVIMIENTOS ORDER BY FECHA NULLS FIRST;

--VARIABLES DE SUSTITUCION
