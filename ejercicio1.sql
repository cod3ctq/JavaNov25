--EN ESTE COMANDO NOSOTROS LE DAMOS EL ALEAS (PRECIO_CON_IVA)
SELECT MONTO, MONTO*1.16 AS PRECIO_CON_IVA FROM MOVIMIENTOS;

--CONCATENACION DE TEXTOS
--EN ESTE RENGLON DE CODIGO HACEMOS UNA NUEVA COLUMNA LLAMADA"FECHA Y MONTO" DONDE UNIMOS LOS 
--VALORES DE LAS COLUMNAS (FECHA Y MONTO) DE LA TABLA MOVIMIENTOS
SELECT MONTO, FECHA, MONTO|| '-' || FECHA "FECHA Y MONTO" FROM MOVIMIENTOS;

